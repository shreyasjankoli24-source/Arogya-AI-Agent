"""Arogya AI - Audit Event API Schemas.

Module 3, Phase 3.4: Pydantic Request/Response Schemas & Data Contracts.
Defines response contracts and query filters for system audit inspection.
Governance Principles:
- Audit records are immutable system telemetry generated by server middleware/services.
- Clients cannot create, modify, or rewrite audit records via API endpoints.
- Event metadata strictly omits credentials, authentication tokens, and PHI.
"""

from datetime import datetime
from typing import Any
from uuid import UUID
from pydantic import Field, field_validator
from backend.app.schemas.common import BaseSchema, ORMModel, ensure_timezone_aware


class AuditEventResponse(ORMModel):
    """Response contract representing an immutable system audit record."""

    id: UUID = Field(
        description="Unique audit event identifier",
    )
    event_type: str = Field(
        description="Event classification (e.g. 'user.login', 'case.created', 'analysis.started')",
    )
    actor_id: UUID | None = Field(
        default=None,
        description="Identifier of initiating user account (None if autonomous system task)",
    )
    action: str = Field(
        description="Action classification ('create', 'read', 'update', 'delete', 'execute')",
    )
    resource_type: str | None = Field(
        default=None,
        description="Target resource category ('patient', 'encounter', 'asset', 'analysis_run')",
    )
    resource_id: str | None = Field(
        default=None,
        description="Identifier of affected resource",
    )
    description: str | None = Field(
        default=None,
        description="Human-readable event summary",
    )
    ip_address: str | None = Field(
        default=None,
        description="Client network IP address",
    )
    event_metadata: dict[str, Any] | None = Field(
        default=None,
        description="Operational context (e.g. request_id, duration); strictly excludes credentials and PHI",
    )
    created_at: datetime = Field(
        description="Event recorded timestamp in UTC",
    )


class AuditEventFilter(BaseSchema):
    """Request query contract for filtering system audit events."""

    event_type: str | None = Field(
        default=None,
        max_length=64,
        description="Filter by specific event classification",
    )
    actor_id: UUID | None = Field(
        default=None,
        description="Filter events initiated by specific user UUID",
    )
    action: str | None = Field(
        default=None,
        max_length=32,
        description="Filter by action type",
    )
    resource_type: str | None = Field(
        default=None,
        max_length=64,
        description="Filter by affected resource category",
    )
    resource_id: str | None = Field(
        default=None,
        max_length=64,
        description="Filter by affected resource UUID/ID",
    )
    start_time: datetime | None = Field(
        default=None,
        description="Lower temporal boundary in ISO 8601 UTC",
    )
    end_time: datetime | None = Field(
        default=None,
        description="Upper temporal boundary in ISO 8601 UTC",
    )

    @field_validator("start_time", "end_time")
    @classmethod
    def validate_filter_timezones(cls, v: datetime | None) -> datetime | None:
        """Enforce timezone awareness on audit query filter boundaries."""
        return ensure_timezone_aware(v)
